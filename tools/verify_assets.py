#!/usr/bin/env python3
"""
tools/verify_assets.py
Deterministic SHA-256 Disc Verifier and C++ Manifest Generator for:
Left 4 Dead 2 (World) (En,Ja,Fr,De,Es,It,Pt,Zh,Ko,Pl,Ru)
Redump ID #12497 | Title ID: 454108D4 | Media ID: 0E79403B
"""

import argparse
import hashlib
import json
import os
import pathlib
import struct
import sys

TITLE_ID_RETAIL = 0x454108D4
TITLE_ID_DEMO = 0x454188D6
MEDIA_ID_RETAIL = 0x0E79403B

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST_JSON = ROOT / "l4d2_disc_manifest.json"
OUTPUT_HEADER = ROOT / "src" / "l4d2_manifest.h"


def parse_xex_title_info(xex_bytes: bytes) -> tuple[int, int, int]:
    """Extracts (title_id, media_id, version) from XEX2 execution info."""
    if not xex_bytes.startswith(b"XEX2"):
        raise ValueError("Invalid XEX2 header")
    n_opt = struct.unpack_from(">I", xex_bytes, 0x14)[0]
    opt_headers = {}
    for i in range(n_opt):
        k, v = struct.unpack_from(">II", xex_bytes, 0x18 + i * 8)
        opt_headers[k] = v

    exec_info_offset = opt_headers.get(0x00040006)
    if not exec_info_offset:
        raise ValueError("XEX2 missing execution info (0x00040006)")

    media_id, version, base_version, title_id, platform, exec_table, disc_num, disc_count = struct.unpack_from(
        ">IIIIBBBB", xex_bytes, exec_info_offset
    )
    return title_id, media_id, version


def generate_cpp_manifest(manifest_data: dict, out_header: pathlib.Path):
    """Generates a hardened C++ header containing the disc verification table."""
    title_id = int(manifest_data["title_id"], 16)
    media_id = int(manifest_data["media_id"], 16)
    files = manifest_data["files"]

    lines = [
        "// Automatically generated by tools/verify_assets.py - DO NOT EDIT MANUALLY",
        "// Left 4 Dead 2 (World) - Redump #12497 Verification Manifest",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <string_view>",
        "#include <array>",
        "",
        "namespace l4d2 {",
        "",
        f"constexpr uint32_t kTargetTitleId = 0x{title_id:08X};",
        f"constexpr uint32_t kTargetMediaId = 0x{media_id:08X};",
        f"constexpr uint32_t kDemoTitleId   = 0x{TITLE_ID_DEMO:08X};",
        f"constexpr size_t   kExpectedFileCount = {len(files)};",
        "",
        "struct DiscFileInfo {",
        "    const char* relative_path;",
        "    uint64_t expected_size;",
        "    const char* expected_sha256;",
        "};",
        "",
        f"inline constexpr std::array<DiscFileInfo, {len(files)}> kDiscManifest = {{{{"
    ]

    for rel_path, meta in sorted(files.items()):
        sz = meta["size"]
        sha = meta["sha256"]
        clean_path = rel_path.replace("\\", "/")
        lines.append(f'    {{"{clean_path}", {sz}ULL, "{sha}"}},')

    lines.extend([
        "}};",
        "",
        "} // namespace l4d2",
        ""
    ])

    out_header.parent.mkdir(parents=True, exist_ok=True)
    with open(out_header, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"[verify_assets] Generated C++ manifest at {out_header} with {len(files)} files.")


def verify_directory(game_dir: pathlib.Path, manifest_data: dict) -> bool:
    """Verifies all files in game_dir against manifest_data."""
    print(f"[verify_assets] Verifying game directory: {game_dir}")
    default_xex = game_dir / "default.xex"
    if not default_xex.is_file():
        print(f"[ERROR] default.xex not found in {game_dir}")
        return False

    with open(default_xex, "rb") as f:
        title_id, media_id, version = parse_xex_title_info(f.read())

    print(f"  Detected Title ID : 0x{title_id:08X}")
    print(f"  Detected Media ID : 0x{media_id:08X}")
    print(f"  Detected Version  : 0x{version:08X}")

    if title_id == TITLE_ID_DEMO:
        print("[WARNING] Supplied directory is Left 4 Dead 2 Demo (454188D6)! Full campaign files are missing.")
    elif title_id != TITLE_ID_RETAIL:
        print(f"[WARNING] Title ID 0x{title_id:08X} does not match Retail World (0x{TITLE_ID_RETAIL:08X}).")

    if media_id != MEDIA_ID_RETAIL:
        print(f"[WARNING] Media ID 0x{media_id:08X} does not match 0x{MEDIA_ID_RETAIL:08X}.")

    files = manifest_data["files"]
    passed = 0
    missing = 0
    corrupt = 0

    for rel_path, meta in files.items():
        local_p = game_dir / rel_path
        if not local_p.is_file():
            # Check backslash/forward slash variant
            local_p = game_dir / rel_path.replace("/", "\\")
        if not local_p.is_file():
            print(f"  [MISSING] {rel_path}")
            missing += 1
            continue

        local_sz = local_p.stat().st_size
        if local_sz != meta["size"]:
            print(f"  [SIZE MISMATCH] {rel_path}: got {local_sz}, expected {meta['size']}")
            corrupt += 1
            continue

        h = hashlib.sha256()
        with open(local_p, "rb") as f:
            while chunk := f.read(1024 * 1024):
                h.update(chunk)
        digest = h.hexdigest()

        if digest != meta["sha256"]:
            print(f"  [HASH MISMATCH] {rel_path}")
            corrupt += 1
        else:
            passed += 1

    print(f"\n[Verification Summary]")
    print(f"  Verified Files : {passed}/{len(files)}")
    print(f"  Missing Files  : {missing}")
    print(f"  Corrupt Files  : {corrupt}")

    if corrupt == 0 and missing == 0:
        print(f"  Status: PASSED (Verified: Title 454108D4 • Media 0E79403B)")
        return True
    else:
        print(f"  Status: INCOMPLETE or MODIFIED")
        return False


def main():
    parser = argparse.ArgumentParser(description="L4D2 Disc Asset Verifier & Manifest Tool")
    parser.add_argument("--dir", type=pathlib.Path, help="Directory to verify")
    parser.add_argument("--gen-header", action="store_true", help="Generate src/l4d2_manifest.h")
    args = parser.parse_args()

    if not MANIFEST_JSON.is_file():
        print(f"[ERROR] Manifest JSON {MANIFEST_JSON} not found!")
        sys.exit(1)

    with open(MANIFEST_JSON, "r", encoding="utf-8") as f:
        manifest_data = json.load(f)

    if args.gen_header or not OUTPUT_HEADER.is_file():
        generate_cpp_manifest(manifest_data, OUTPUT_HEADER)

    if args.dir:
        success = verify_directory(args.dir, manifest_data)
        if not success:
            sys.exit(1)


if __name__ == "__main__":
    main()

